// Bundles the UI + net layers into dist/index.html + dist/app.js (+ dist/cards.json).
// Picks the real engine when src/engine/game.ts exports the contract, else the UI mock (src/ui/mock.ts).
// Run: npx tsx tools/bundle.ts [--dev] [--mock] [--dev-images]
// Card images: data/images/<printedCode>.webp are packed into sprite atlases dist/atlas/<n>.webp (see below).
// --dev-images (or RIFTFORGE_DEV_IMAGES=1) also packs placeholder art from data/images-dev/ (tools/fake-images.ts)
// for codes the real images lack; a normal build rebuilds the atlases without them, so placeholders never linger.
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dev = process.argv.includes('--dev');
const forceMock = process.argv.includes('--mock') || process.env.RIFTFORGE_MOCK === '1';
const devImages = process.argv.includes('--dev-images') || process.env.RIFTFORGE_DEV_IMAGES === '1';

function engineSource(): 'real' | 'mock' {
  if (forceMock) return 'mock';
  const game = join(root, 'src/engine/game.ts');
  if (!existsSync(game)) return 'mock';
  const src = readFileSync(game, 'utf8');
  const need = ['createGame', 'getPending', 'getLegalActions', 'applyAction', 'getView'];
  const ok = need.every(n => new RegExp(`export\\s+(?:async\\s+)?(?:function|const|let)\\s+${n}\\b|export\\s*\\{[^}]*\\b${n}\\b`).test(src));
  return ok ? 'real' : 'mock';
}

const src = engineSource();
const hasBot = existsSync(join(root, 'src/engine/bot.ts'));
const deckMod = ['src/engine/deck.ts', 'src/engine/decks.ts', 'src/engine/deckValidation.ts', 'src/engine/validate.ts'].find(f => existsSync(join(root, f)));
const gen = src === 'real'
  ? `// GENERATED by tools/bundle.ts — real engine selected.\nimport '../engine/index';\nexport * as engine from '../engine/game';\nexport * as bot from '${hasBot ? '../engine/bot' : './mock'}';\nexport * as deck from '${deckMod ? '../' + deckMod.replace(/^src\//, '').replace(/\.ts$/, '') : '../engine/game'}';\nexport * as registry from '../cards/registry';\nexport const ENGINE_SOURCE = 'engine';\n`
  : `// GENERATED by tools/bundle.ts — selects the real engine when src/engine/game.ts exists, else the UI mock.\nexport * as engine from './mock';\nexport * as bot from './mock';\nexport * as deck from './mock';\nexport const registry = { allScripts: (): unknown[] => [] };\nexport const ENGINE_SOURCE = 'mock';\n`;
const genPath = join(root, 'src/ui/engine-impl.gen.ts');
if (!existsSync(genPath) || readFileSync(genPath, 'utf8') !== gen) writeFileSync(genPath, gen);

mkdirSync(join(root, 'dist'), { recursive: true });
const result = await build({
  entryPoints: [join(root, 'src/ui/entry.ts')],
  bundle: true, format: 'iife', target: ['es2022'], platform: 'browser',
  minify: !dev, sourcemap: false, legalComments: 'none',
  loader: { '.css': 'text' },
  outfile: join(root, 'dist/app.js'),
  metafile: true, logLevel: 'warning',
});
const js = readFileSync(join(root, 'dist/app.js'), 'utf8');

const html = `<!DOCTYPE html>
<html lang="en" data-theme="dark">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Riftforge</title>
<meta name="description" content="Riftforge — a fully automated digital table for the Riftbound TCG.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700;800&family=Marcellus+SC&display=swap">
<style>html,body{margin:0;background:#0d1016;color:#ebe7df;font-family:system-ui,sans-serif}:root[data-theme=light] body{background:#efe8dc;color:#221d16}</style>
</head>
<body>
<div id="app"></div>
<noscript>Riftforge needs JavaScript.</noscript>
<script src="app.js"></script>
</body>
</html>
`;
writeFileSync(join(root, 'dist/index.html'), html);
// Card data beside the page (fetched by relative path).
const cards = join(root, 'data/cards.json');
if (existsSync(cards)) copyFileSync(cards, join(root, 'dist/cards.json'));
else console.warn('data/cards.json missing — the page will start with no cards.');
// ---- card images: sprite atlases ----
// dist/atlas/<n>.webp: plain WebP images, published as the artifact's own files (reviewable, served same-origin).
// Portrait cards are 320x447 cells in a 6x6 grid (1920x2682 px); battlefields are 447x320 cells in their own
// atlases. Codes are packed set by set (base printings before alt arts), so a game's cards cluster into few atlases.
// dist/images-manifest.json v3 = {format:'atlas', v:3, count, totalBytes, dev, key, atlases:[{path, w, h,
// cell:[cw,ch], bytes, count, codes:{printedCode:[col,row]}}]}. The page draws a cell to a canvas -> blob: URL
// (src/ui/art.ts). `key` hashes the sources + layout: an unchanged key reuses the existing atlas files (sharp
// encoding is deterministic, so a rebuild gives the same bytes anyway). Old dist/images/ zips/packs are removed.
const IMG_RE = /^[a-z0-9][a-z0-9-]{0,47}\.webp$/;
const PORTRAIT = { cw: 320, ch: 447, cols: 6, rows: 6 };
const LANDSCAPE = { cw: 447, ch: 320, cols: 6, rows: 6 };
const QUALITY = 80;
const ATLAS_MAX = 3 * 1024 * 1024;
const distAtlas = join(root, 'dist/atlas');
const realDir = join(root, 'data/images');
const devDir = join(root, 'data/images-dev');
const listImgs = (dir: string) => existsSync(dir) ? readdirSync(dir).filter(f => IMG_RE.test(f)) : [];
const sources = new Map<string, string>(); // code -> file
for (const f of listImgs(realDir)) sources.set(f.slice(0, -5), join(realDir, f));
let devCount = 0;
if (devImages) for (const f of listImgs(devDir)) if (!sources.has(f.slice(0, -5))) { sources.set(f.slice(0, -5), join(devDir, f)); devCount++; }
// the old per-set zip / pack / loose-webp output is gone for good
const oldImg = join(root, 'dist/images');
if (existsSync(oldImg)) {
  for (const f of readdirSync(oldImg)) if (IMG_RE.test(f) || /\.(pack|zip)$/.test(f) || f === 'manifest.json' || f === '.dev-placeholders.json') rmSync(join(oldImg, f), { force: true });
  if (!readdirSync(oldImg).length) rmSync(oldImg, { recursive: true, force: true });
}

interface AtlasInfo { path: string; w: number; h: number; cell: [number, number]; bytes: number; count: number; codes: Record<string, [number, number]> }
const isAlt = (code: string) => /^[a-z]+-(?:[a-z]*\d+)[a-z]+(?:-|$)/.test(code);
const order = (a: string, b: string) => { const sa = a.split('-')[0], sb = b.split('-')[0]; return sa !== sb ? (sa < sb ? -1 : 1) : (+isAlt(a) - +isAlt(b)) || (a < b ? -1 : a > b ? 1 : 0); };
const portrait: string[] = [], landscape: string[] = [];
const hash = createHash('sha256').update(JSON.stringify({ PORTRAIT, LANDSCAPE, QUALITY, v: 3, flatten: '#000', effort: 4 }));
const sharpMod = sources.size ? (await import('sharp')).default : null;
for (const code of [...sources.keys()].sort(order)) {
  const buf = readFileSync(sources.get(code)!);
  hash.update(code).update(createHash('sha256').update(buf).digest());
  const m = await sharpMod!(buf).metadata();
  ((m.width ?? 0) > (m.height ?? 0) ? landscape : portrait).push(code);
}
const key = hash.digest('hex').slice(0, 24);
const manifestPath = join(root, 'dist/images-manifest.json');
let atlases: AtlasInfo[] = [];
let reused = false;
try {
  const old = JSON.parse(readFileSync(manifestPath, 'utf8')) as { format?: string; key?: string; atlases?: AtlasInfo[] };
  if (old.format === 'atlas' && old.key === key && old.atlases?.length && old.atlases.every(a => existsSync(join(root, 'dist', a.path)) && statSync(join(root, 'dist', a.path)).size === a.bytes)) { atlases = old.atlases; reused = true; }
} catch { /* no usable previous manifest */ }
if (!reused && sources.size) {
  const plan: { codes: string[]; g: typeof PORTRAIT }[] = [];
  for (const [list, g] of [[portrait, PORTRAIT], [landscape, LANDSCAPE]] as const)
    for (let i = 0; i < list.length; i += g.cols * g.rows) plan.push({ codes: list.slice(i, i + g.cols * g.rows), g });
  mkdirSync(distAtlas, { recursive: true });
  const build1 = async (n: number) => {
    const { codes, g } = plan[n];
    const cols = Math.min(g.cols, codes.length), rows = Math.ceil(codes.length / g.cols);
    const w = cols * g.cw, h = rows * g.ch;
    const map: Record<string, [number, number]> = {};
    const layers = await Promise.all(codes.map(async (code, i) => {
      const col = i % g.cols, row = Math.floor(i / g.cols);
      map[code] = [col, row];
      const input = await sharpMod!(sources.get(code)!).resize(g.cw, g.ch, { fit: 'fill' }).flatten({ background: '#000' }).raw().toBuffer();
      return { input, raw: { width: g.cw, height: g.ch, channels: 3 as const }, left: col * g.cw, top: row * g.ch };
    }));
    let q = QUALITY, out: Buffer;
    for (;;) {
      out = await sharpMod!({ create: { width: w, height: h, channels: 3, background: '#000' } }).composite(layers).webp({ quality: q, effort: 4, smartSubsample: true }).toBuffer();
      if (out.length <= ATLAS_MAX || q <= 50) break;
      q -= 5;
    }
    const path = `atlas/${n}.webp`;
    writeFileSync(join(root, 'dist', path), out);
    return { path, w, h, cell: [g.cw, g.ch] as [number, number], bytes: out.length, count: codes.length, codes: map };
  };
  atlases = new Array(plan.length);
  let next = 0;
  await Promise.all(Array.from({ length: 4 }, async () => { while (next < plan.length) { const n = next++; atlases[n] = await build1(n); } }));
}
// drop atlas files that are not in the manifest (fewer atlases than last time)
const keep = new Set(atlases.map(a => a.path.slice(6)));
if (existsSync(distAtlas)) for (const f of readdirSync(distAtlas)) if (!keep.has(f)) rmSync(join(distAtlas, f), { force: true });
if (!atlases.length && existsSync(distAtlas)) rmSync(distAtlas, { recursive: true, force: true });
const totalBytes = atlases.reduce((a, p) => a + p.bytes, 0);
if (atlases.length) writeFileSync(manifestPath, JSON.stringify({ format: 'atlas', v: 3, count: sources.size, totalBytes, dev: devCount > 0, key, atlases }));
else rmSync(manifestPath, { force: true });
const imgNote = atlases.length ? ` images=${sources.size} in ${atlases.length} atlases (${(totalBytes / 1048576).toFixed(1)} MB${reused ? ', unchanged' : ''}${devCount ? `, ${devCount} DEV placeholders` : ''})` : ' images=none (text frames)';

console.log(`bundle: engine=${src}${src === 'real' ? ` bot=${hasBot ? 'engine' : 'mock'} deck=${deckMod ?? 'game.ts/mock'}` : ''} app.js=${(js.length / 1024).toFixed(0)}KB${existsSync(cards) ? ' cards.json copied' : ''}${imgNote}`);
