// Card-script coverage report.
// Loads data/cards.json and the card registry (after importing src/cards/scripts/index.ts) and prints, per
// scripting batch (data/card-batches.json) and overall:
//   - cards scripted / keyword-only / unscripted
//   - cards whose script text differs from the cards.json `text`
//   - cards with no test (their id doesn't appear anywhere under tests/cards)
// and writes docs/coverage.md.
// Run: npx tsx tools/coverage.ts            (add --quiet to only write the file)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import '../src/cards/scripts/index.ts';
import { getScript } from '../src/cards/registry.ts';
import type { CardScript } from '../src/engine/abilities.ts';

interface CardJson { id: string; name: string; subtitle?: string; type: string; text: string; keywords: string[] }
interface Analysis { scriptNeed: 'script' | 'keywords-only' | 'none' | 'reminder-only'; intrinsicKeywords?: string[] }
interface BatchFile { keywordsOnly: string[]; batches: { id: string; title: string; cards: string[] }[] }

const root = new URL('..', import.meta.url).pathname;
const read = (p: string) => readFileSync(join(root, p), 'utf8');
const cards: Record<string, CardJson> = JSON.parse(read('data/cards.json'));
const analysis: Record<string, Analysis> = JSON.parse(read('data/card-analysis.json'));
const batchFile: BatchFile = JSON.parse(read('data/card-batches.json'));

// ---- all test sources under tests/cards ----
function walk(dir: string, out: string[] = []): string[] {
  let names: string[] = [];
  try { names = readdirSync(dir); } catch { return out; }
  for (const n of names) {
    const p = join(dir, n);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (/\.(ts|js|mjs)$/.test(n)) out.push(p);
  }
  return out;
}
const testFiles = walk(join(root, 'tests/cards'));
const testText = testFiles.map(f => readFileSync(f, 'utf8')).join('\n');

type Status = 'scripted' | 'keyword-only' | 'unscripted';
interface Row { id: string; name: string; status: Status; note?: string; textDiffers: boolean; tested: boolean }

function hasContent(s: CardScript | undefined): boolean {
  if (!s) return false;
  return s.abilities.length > 0 || !!s.keywords || !!s.costs || s.entersReady !== undefined || !!s.additionalCosts?.length || s.maxEmpower !== undefined;
}

function rowFor(id: string): Row {
  const c = cards[id];
  const a = analysis[id];
  const s = getScript(id);
  const name = c ? (c.subtitle ? `${c.name}, ${c.subtitle}` : c.name) : id;
  let status: Status;
  let note: string | undefined;
  const need = a?.scriptNeed ?? 'script';
  if (hasContent(s)) status = 'scripted';
  else if (need !== 'script') status = 'keyword-only';
  else { status = 'unscripted'; if (s) note = 'registered with no abilities'; }
  const textDiffers = !!s && !!c && s.text !== c.text;
  const tested = testText.includes(id);
  return { id, name, status, note, textDiffers, tested };
}

interface Summary { id: string; title: string; rows: Row[] }
const summaries: Summary[] = batchFile.batches.map(b => ({ id: b.id, title: b.title, rows: b.cards.map(rowFor) }));
summaries.push({ id: 'B0-keywords-only', title: 'Cards whose whole text is generic keywords', rows: batchFile.keywordsOnly.map(rowFor) });
const inBatches = new Set(summaries.flatMap(s => s.rows.map(r => r.id)));
const others = Object.keys(cards).filter(id => !inBatches.has(id));
summaries.push({ id: 'other', title: 'Cards in no batch (no rules text needing a script)', rows: others.map(rowFor) });

function counts(rows: Row[]) {
  return {
    total: rows.length,
    scripted: rows.filter(r => r.status === 'scripted').length,
    keywordOnly: rows.filter(r => r.status === 'keyword-only').length,
    unscripted: rows.filter(r => r.status === 'unscripted').length,
    textDiffers: rows.filter(r => r.textDiffers).length,
    untested: rows.filter(r => !r.tested).length,
  };
}

const all = summaries.flatMap(s => s.rows);
const lines: string[] = [];
lines.push('# Card script coverage');
lines.push('');
lines.push('Generated by `npx tsx tools/coverage.ts` from data/cards.json, data/card-batches.json and the card registry');
lines.push('(src/cards/scripts/index.ts). "tested" means the card id appears in a file under tests/cards.');
lines.push('');
lines.push('| batch | cards | scripted | keyword-only | unscripted | text differs | no test |');
lines.push('|---|---:|---:|---:|---:|---:|---:|');
for (const s of [...summaries, { id: '**overall**', title: '', rows: all }]) {
  const c = counts(s.rows);
  lines.push(`| ${s.id} | ${c.total} | ${c.scripted} | ${c.keywordOnly} | ${c.unscripted} | ${c.textDiffers} | ${c.untested} |`);
}
lines.push('');
const list = (title: string, rows: Row[], fmt: (r: Row) => string) => {
  if (!rows.length) return;
  lines.push(`<details><summary>${title} (${rows.length})</summary>`);
  lines.push('');
  for (const r of rows) lines.push(`- ${fmt(r)}`);
  lines.push('');
  lines.push('</details>');
  lines.push('');
};
for (const s of summaries) {
  const c = counts(s.rows);
  if (!c.total) continue;
  lines.push(`## ${s.id}`);
  lines.push('');
  if (s.title) { lines.push(s.title); lines.push(''); }
  list('Unscripted', s.rows.filter(r => r.status === 'unscripted'), r => `\`${r.id}\` ${r.name}${r.note ? ` — ${r.note}` : ''}`);
  list('Script text differs from cards.json', s.rows.filter(r => r.textDiffers), r => `\`${r.id}\` ${r.name}: script \`${JSON.stringify(getScript(r.id)!.text)}\` vs card \`${JSON.stringify(cards[r.id]?.text)}\``);
  list('No test', s.rows.filter(r => !r.tested), r => `\`${r.id}\` ${r.name} (${r.status})`);
}
const md = lines.join('\n') + '\n';
writeFileSync(join(root, 'docs/coverage.md'), md);

if (!process.argv.includes('--quiet')) {
  const pad = (s: string | number, n: number) => String(s).padEnd(n);
  console.log(`${pad('batch', 34)}${pad('cards', 7)}${pad('script', 8)}${pad('kw-only', 9)}${pad('unscr', 7)}${pad('textΔ', 7)}no test`);
  for (const s of [...summaries, { id: 'overall', title: '', rows: all }]) {
    const c = counts(s.rows);
    console.log(`${pad(s.id, 34)}${pad(c.total, 7)}${pad(c.scripted, 8)}${pad(c.keywordOnly, 9)}${pad(c.unscripted, 7)}${pad(c.textDiffers, 7)}${c.untested}`);
  }
  const bad = all.filter(r => r.textDiffers);
  if (bad.length) { console.log(`\nScript text differs (${bad.length}):`); for (const r of bad.slice(0, 50)) console.log(`  ${r.id} ${r.name}`); }
  console.log('\nwrote docs/coverage.md');
}
